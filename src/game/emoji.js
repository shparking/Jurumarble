// 규칙에 안 걸리는 텍스트용 — 텍스트마다 항상 같은 이모지가 나오도록 해시로 고름
const POOL = ['🎲', '🎯', '🎪', '🎈', '🎁', '🃏', '🪩', '🌈', '⭐', '💥', '🍀', '🎊', '🦊', '🐸', '🐙', '🦄', '🍑', '🍒', '🥑', '🌶️', '🧃', '🪄', '🎷', '🥁']
function hashPick(text) {
  let h = 0
  for (let i = 0; i < text.length; i++) h = (h * 31 + text.charCodeAt(i)) >>> 0
  return POOL[h % POOL.length]
}

export function autoEmoji(text, fallback = '🎲') {
  const t = (text || '').trim()
  if (!t) return fallback
  for (const [re, e] of RULES) if (re.test(t)) return e
  return hashPick(t)
}
